import {readFile,writeFile,access} from 'node:fs/promises';
import {resolve,dirname} from 'node:path';
import {execFile} from 'node:child_process';
import {promisify} from 'node:util';
import {createHash} from 'node:crypto';
import {editorialNarration} from '../src/analysis/editorial-narration.mjs';
const run=promisify(execFile),[manifestPath,output]=process.argv.slice(2);
if(!manifestPath||!output)throw Error('EDITORIAL_BUILD_ARGUMENTS_REQUIRED');
const base=dirname(resolve(manifestPath)),manifest=JSON.parse(await readFile(manifestPath,'utf8'));
const script=name=>new URL(name,import.meta.url).pathname;
const invoke=(name,args)=>run(process.execPath,[script(name),...args],{timeout:600000,maxBuffer:200000});
const exists=path=>access(path).then(()=>true,()=>false);
if(await exists(resolve(output)))throw Error('OUTPUT_ALREADY_EXISTS');
if(!manifest.quote?.source||!manifest.quote.path||!manifest.narrationText||manifest.narrationText.length>650)throw Error('EDITORIAL_BUILD_MANIFEST_INVALID');
const quote=resolve(base,manifest.quote.path);
if(!await exists(quote))await invoke('fetch-editorial-quote.mjs',[manifest.quote.source.videoId,String(manifest.quote.source.start),String(manifest.quote.source.end),quote]);
const audio=resolve(base,manifest.narration?.path??'maya-approved-115.mp3');
if(!await exists(audio))await invoke('editorial-narration.mjs',[audio,manifest.narrationText]);
else if(manifest.narration?.voice!=='Maya'||manifest.narration?.speed!==1.15||manifest.narration?.sha256!==createHash('sha256').update(await readFile(audio)).digest('hex'))throw Error('EDITORIAL_VOICE_LOCKED');
manifest.narration={provider:'soniox',...editorialNarration,path:audio,sha256:createHash('sha256').update(await readFile(audio)).digest('hex')};
const prepared=resolve(base,'prepared-montage.json');await writeFile(prepared,JSON.stringify(manifest,null,2));
await invoke('render-editorial.mjs',[prepared,resolve(output)]);
console.log(resolve(output));
